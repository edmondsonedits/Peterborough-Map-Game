'use strict';
// The readable city catalog is authoritative. Legacy rows are migration baselines only.
const fs=require('node:fs'),path=require('node:path'),zlib=require('node:zlib');
const root=path.resolve(__dirname,'..');
const read=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
const catalog=read('cities/peterborough/locations.json');
const legacy=read('cities/peterborough/legacy-dispatch-1.4.20.json');
const byId=new Map(legacy.map(c=>[c.id,c]));
const medical=[...new Set(legacy.filter(c=>c.main==='Medical').map(c=>c.sub))];
const fire=['Structure Fire','Alarms No Apparent Problem','Motor Vehicle Collision'];
const locations=catalog.locations.map((c,i)=>{
  const prior=c.sourceCallIds.map(id=>byId.get(id)).filter(Boolean), first=prior[0];
  const incidentProfiles={
    fire:{sub:prior.find(c=>c.main==='Fire')?.sub||fire[i%fire.length]},
    ems:{sub:prior.find(c=>c.main==='Medical')?.sub||medical[i%medical.length]},
  };
  const main=first?.main||(i%2?'Medical':'Fire');
  return {id:c.id,main,sub:first?.sub||incidentProfiles[main==='Medical'?'ems':'fire'].sub,
    name:c.name||'',addr:c.address,lat:c.lat,lng:c.lng,radius:c.radiusMeters,
    confirmed:true,sources:['shared-editor','geo-guesser','driving-simulator'],custom:false,
    recognitionDifficulty:c.difficulty,crossStreets:c.crossStreets,sourceCallIds:c.sourceCallIds,incidentProfiles};
});
const counts=Object.fromEntries(['easy','medium','hard'].map(t=>[t,locations.filter(c=>c.recognitionDifficulty===t).length]));
if(JSON.stringify(counts)!==JSON.stringify({easy:100,medium:50,hard:50})||new Set(locations.map(c=>c.id)).size!==200)throw new Error('Invalid catalog totals/IDs');
const compress=data=>zlib.gzipSync(JSON.stringify(data),{level:9}).toString('base64');
fs.writeFileSync(path.join(root,'shared/dispatch-data-1.4.4.js'),`/* Generated by scripts/build-dispatch-catalog.cjs. Edit cities/peterborough/locations.json. */
(() => {
  'use strict';
  const VERSION = '1.6.108';
  const PAYLOAD = '${compress(locations)}';
  const LEGACY_PAYLOAD = '${compress(legacy)}';
  async function decode(encoded) {
    const bytes=Uint8Array.from(atob(encoded),c=>c.charCodeAt(0));
    return JSON.parse(await new Response(new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'))).text());
  }
  window.PTBO_DISPATCH_DATA_VERSION = VERSION;
  window.PTBO_DISPATCH_DATA_READY = Promise.all([decode(PAYLOAD),decode(LEGACY_PAYLOAD)]).then(([locations,legacy])=>{
    window.PTBO_DISPATCH_LEGACY_LOCATIONS=legacy;
    window.PTBO_DISPATCH_LOCATIONS=locations;
    return locations;
  });
})();
`);
console.log('Built shared dispatch catalog:',counts);
