import assert from 'node:assert/strict';
import * as THREE from '../city-explorer/vendor/three-r180/build/three.module.min.js';
import { createAIEditorCamera } from '../city-explorer/editor/ai-editor-camera.js';
import { createEditorCameraNavigation } from '../city-explorer/editor/editor-camera-navigation.js';
const camera=new THREE.PerspectiveCamera(55,1.5,0.1,20000);camera.position.set(0,10,20);camera.lookAt(0,0,0);
const navigation=createEditorCameraNavigation(THREE,camera,{width:900,height:600});navigation.reset(new THREE.Vector3());
const memory=new Map();let writesFail=false;
const storage={getItem:key=>memory.get(key)||null,setItem:(key,value)=>{if(writesFail)throw Error('quota');memory.set(key,value);}};
const adapter={THREE,camera,navigation:()=>navigation,storage,project:(lat,lon)=>({x:(lon+78.32)*80000,y:(44.30-lat)*110000}),heightAt:()=>5};
const tools=createAIEditorCamera(adapter);
tools.run({op:'camera',latitude:44.30,longitude:-78.32,altitude:20,distance:50,bearing:90});
assert.ok(Math.abs(camera.position.x-50)<1e-8);assert.equal(camera.position.y,25);
tools.run({op:'view.save',name:'Bridge side'});const saved=tools.inspect();
tools.run({op:'camera',latitude:44.31,longitude:-78.33,altitude:50,distance:100,bearing:180});
tools.run({op:'view.restore',name:'Bridge side'});
assert.deepEqual(tools.inspect(),saved);
assert.equal(createAIEditorCamera(adapter).run({op:'view.list'}).length,1,'views persist across editor reload');
const previous=camera.position.toArray();
assert.throws(()=>tools.run({op:'camera',latitude:44.30,longitude:-78.32,distance:-1}));assert.deepEqual(camera.position.toArray(),previous);
assert.throws(()=>tools.run({op:'view.restore',name:'missing'}));
writesFail=true;const failed=tools.run({op:'view.save',name:'Memory only'});assert.equal(failed.persisted,false);
assert.equal(tools.run({op:'view.list'}).length,2);
const mesh=new THREE.Mesh(new THREE.BoxGeometry(20,10,5));mesh.position.set(100,10,100);mesh.updateMatrixWorld();
tools.focus(mesh);assert.deepEqual(navigation.target.toArray(),[100,10,100]);
const corrupt=createAIEditorCamera({...adapter,storage:{getItem:()=>'{bad',setItem(){}}});assert.deepEqual(corrupt.run({op:'view.list'}),[]);
console.log('AI editor geographic camera, exact view restoration, focus and storage failure checks passed.');
